package day09;

import java.io.*;

public class Day09_05 {

	public static void main(String[] args)
	throws IOException{
		BufferedReader br =
				new BufferedReader(new InputStreamReader(System.in));
		
		int num=0;
		
		
		System.out.print("점수입력:");
		num = Integer.parseInt(br.readLine());
		System.out.println("점수:"+num+"점");
		

	}

}
